TEST(Psi, MatchesFiftyDigitQuadrature) {
  double worst = 0.0;
  for (const PsiCase& c : kCases) {
    const double got = pulselob::core::psi(c.n, c.x, std::exp(-c.x));
    const double ref = static_cast<double>(c.ref);
    const double rel = std::fabs(got - ref) / std::fabs(ref);
    worst = std::fmax(worst, rel);
    EXPECT_LT(rel, 1e-14) << "n=" << c.n << " x=" << c.x;
  }
  RecordProperty("worst_relative_error", pulselob::testkit::sci(worst));
}

TEST(Psi, AllOrdersAgreeWithSingleOrderCalls) {
  std::array<double, 4> v{};
  for (double x : {1e-7, 0.3, 0.9999, 1.0, 4.0}) {
    pulselob::core::psi_upto<3>(x, std::exp(-x), v);
    for (std::size_t n = 0; n < 4; ++n) {
      EXPECT_EQ(v[n], pulselob::core::psi(n, x, std::exp(-x)));
    }
  }
}

TEST(Psi, SeriesAndRecurrenceMeetContinuouslyAtRadius) {
  // Just below and above |x| = 1 the two evaluation rules must agree to rounding.
  for (std::size_t n = 0; n < 4; ++n) {
    const double below =
        pulselob::core::psi(n, std::nextafter(1.0, 0.0), std::exp(-std::nextafter(1.0, 0.0)));
    const double at = pulselob::core::psi(n, 1.0, std::exp(-1.0));
    EXPECT_NEAR(below, at, 1e-15) << "n=" << n;
  }
}

